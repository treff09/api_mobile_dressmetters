def charger(apps, schema_editor):
    LibelleMesure = apps.get_model("core", "LibelleMesure")
    TypeVetement = apps.get_model("core", "TypeVetement")
    par_cle = {}
    for i, m in enumerate(BIBLIOTHEQUE):
        # On réutilise un point système existant portant le même nom
        lib = (LibelleMesure.objects.filter(client_profile__isnull=True, professional_profile__isnull=True,
                                            nom__iexact=m["nom"]).first()
               or LibelleMesure.objects.filter(client_profile__isnull=True, cle=m["cle"]).first())
        nouveau = lib is None
        if nouveau:
            lib = LibelleMesure(nom=m["nom"])
        lib.cle = m["cle"]
        lib.type_mesure = m["type"]
        lib.aide = m["aide"]
        lib.ordre = i
        lib.label_t = m.get("t", 0.5)
        lib.position_x_h, lib.position_y_h = m["x_h"], m["y_h"]
        lib.position_x_f, lib.position_y_f = m["x_f"], m["y_f"]
        lib.fin_x_h, lib.fin_y_h = m.get("fx_h"), m.get("fy_h")
        lib.fin_x_f, lib.fin_y_f = m.get("fx_f"), m.get("fy_f")
        if nouveau:
            lib.position_x, lib.position_y = m["x_h"], m["y_h"]
            lib.afficher_par_defaut = m["cle"] in AFFICHER_PAR_DEFAUT
            lib.categorie = "Bibliothèque"
        lib.save()
        par_cle[m["cle"]] = lib

    for nom, cles in VETEMENTS:
        tv = TypeVetement.objects.filter(professional_profile__isnull=True, nom__iexact=nom).first()
        if tv is None:
            tv = TypeVetement.objects.create(nom=nom)
        if not tv.mesures_requises.exists():
            tv.mesures_requises.set([par_cle[c] for c in cles])


